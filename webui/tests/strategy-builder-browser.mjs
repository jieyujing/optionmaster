import assert from "node:assert/strict";
import { chromium } from "playwright-core";
const executablePath=process.env.OPTIONMASTER_BROWSER_EXECUTABLE;
assert.ok(executablePath,"Existing local Chromium required");
const browser=await chromium.launch({executablePath,headless:true,args:["--disable-background-networking"]});
const results=[];
try{
  const page=await browser.newPage({viewport:{width:1400,height:900}});
  await page.route("**/*",r=>r.abort());
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  await page.setContent('<!doctype html><html><body style="margin:0"><div id="root"></div></body></html>');
  await page.addStyleTag({path:"test-results/d12/ui-fixture.css"});
  await page.addScriptTag({path:"test-results/d12/ui-fixture.js"});
  const waitReady=async()=>{await page.getByText("T 型报价",{exact:true}).waitFor();await page.locator(".sb-chain table").waitFor();};
  await waitReady();
  assert.match(await page.locator(".sb-head").innerText(),/合成测试数据/);
  assert.match(await page.locator(".sb-filters").innerText(),/最新完整交易日未验证/);
  await page.getByLabel("交易日",{exact:true}).selectOption("2022-09-07");
  await waitReady();
  const c1="EX.TEST.F1.C100",p1="EX.TEST.F1.P100",c2="EX.TEST.F2.C100";
  const quote=(id,label)=>page.locator(".sb-chain").getByLabel(id+" "+label,{exact:true});
  const pos=id=>page.getByTestId("position-"+id);
  await quote(c1,"增加数量").click();
  await pos(c1).waitFor();
  assert.match(await page.locator(".sb-chain .qt-symbol").filter({hasText:c1}).getAttribute("title"),/IV 不可用/);
  assert.equal(await page.locator('[data-pane="CALL"] tbody tr').first().locator("td,th").count(),14);
  assert.equal(await page.locator('[data-pane="CENTER"] tbody tr').first().locator("td,th").count(),1);
  assert.equal(await page.locator('[data-pane="PUT"] tbody tr').first().locator("td,th").count(),14);
  await page.getByLabel("PUT 水平滚动",{exact:true}).fill("500");
  await page.waitForFunction(()=>{
    const l=document.querySelector('[data-pane="CALL"]'),r=document.querySelector('[data-pane="PUT"]');
    return Math.abs((l.scrollWidth-l.clientWidth-l.scrollLeft)-r.scrollLeft)<=2;
  });
  await page.getByRole("button",{name:"居中",exact:true}).click();
  assert.equal(await pos(c1).getByLabel(c1+" 建仓价",{exact:true}).inputValue(),"5");
  await quote(p1,"持仓数量").fill("-2");
  await pos(p1).waitFor();
  assert.match(await pos(p1).innerText(),/空头/);
  await quote(p1,"持仓数量").fill("0");await pos(p1).waitFor({state:"detached"});
  results.push("signed quantity, zero removal, IV-independent selection");
  await pos(c1).getByLabel(c1+" 建仓价",{exact:true}).fill("6");
  await quote("EX.TEST.F1","减少数量").click();
  await pos("EX.TEST.F1").waitFor();
  await page.getByLabel("期权链",{exact:true}).selectOption(JSON.stringify(["2022-09-07","EX.TEST.F2"]));
  await waitReady();await quote(c2,"增加数量").click();await pos(c2).waitFor();
  assert.equal(await pos(c1).getByLabel(c1+" 建仓价",{exact:true}).inputValue(),"6");
  results.push("cross-month portfolio and explicit entry");
  await page.getByLabel("交易日",{exact:true}).selectOption("2022-09-08");
  await page.getByRole("button",{name:"保留建仓成本重估",exact:true}).click();
  await waitReady();
  assert.match(await pos(c2).innerText(),/INSTRUMENT_UNAVAILABLE/);
  assert.match(await pos(c1).innerText(),/建仓日 2022-09-07/);
  assert.equal(await pos(c1).getByLabel(c1+" 建仓价",{exact:true}).inputValue(),"6");
  assert.match(await page.getByTestId("portfolio-ready").innerText(),/尚不可计算/);
  results.push("cross-date revalue retains original costs and missing month");
  await page.getByRole("button",{name:"左右分栏",exact:true}).click();
  const divider=page.getByRole("separator",{name:"调整分栏"});
  await divider.focus();await divider.press("ArrowRight");assert.equal(await divider.getAttribute("aria-valuenow"),"60");
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await divider.isVisible(),false);
  results.push("keyboard resizing and narrow viewport");
  await page.getByLabel("品种",{exact:true}).selectOption(JSON.stringify(["EX","OTHER"]));
  await page.getByRole("dialog").waitFor();await page.getByRole("button",{name:"取消",exact:true}).click();
  assert.equal(await pos(c1).count(),1);
  await page.getByLabel("品种",{exact:true}).selectOption(JSON.stringify(["EX","OTHER"]));
  await page.getByRole("button",{name:"重新构建",exact:true}).click();
  await waitReady();assert.equal(await pos(c1).count(),0);
  assert.equal(await page.getByTestId("portfolio-ready").innerText(),"尚未选择持仓");
  assert.equal(await page.getByText("缺失",{exact:true}).count(),1);
  assert.deepEqual(errors,[]);
  results.push("product confirmation, rebuild and absent quote");
  console.log(JSON.stringify({status:"PASS",checks:results},null,2));
}finally{await browser.close();}
